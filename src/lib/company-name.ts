/*
 * 取引先名の表記ゆれ吸収。
 *
 * CRM側は「株)○○」「○○(株」と省略して登録しているが、アプローチリストの
 * 元になるスプレッドシートは「株式会社○○」のままになっている。
 * 文字列の完全一致で照合すると同じ会社が二重に登録されてしまうため、
 * 法人格の表記と記号・空白を落とした形で突き合わせる。
 */

// 「株式会社」とその省略形。長いものから消さないと「株」だけが残るので順番を保つ
const LEGAL_FORMS = [
  "株式会社",
  "有限会社",
  "合同会社",
  "合資会社",
  "合名会社",
  "一般社団法人",
  "一般財団法人",
  "株)",
  "(株",
  "有)",
  "(有",
  "合)",
  "(合",
  "（株",
  "株）",
  "（有",
  "有）",
  "（合",
  "合）",
];

/** 照合用の形に正規化する。表示には使わない（元の表記はそのまま保つ） */
export function normalizeCompanyName(name: string): string {
  let s = name.trim();
  for (const form of LEGAL_FORMS) {
    s = s.split(form).join("");
  }
  // 記号・空白はゆれやすいので落とす（全角半角の括弧・中黒・ハイフン等）
  return s
    .replace(/[\s　()（）・･\-ー—–_,，.。]/g, "")
    .toLowerCase();
}
